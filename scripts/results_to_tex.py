"""./ra results-tex — expose results to the paper as LaTeX macros (the only way numbers enter prose).

Reads results/<id>/metrics.json (nested keys allowed; optional "_format": {"key": ".3f"}) and writes
paper/generated/results.tex with one macro per value, e.g.
    results/sim_main/metrics.json {"mse": 0.01234}  ->  \\resSimMainMse  = 0.0123
Digits in names are spelled out (TeX macro names are letters only): exp2 -> ExpTwo.
Also copies results/<id>/*.tex snippets (e.g. SymPy-generated equations) to paper/generated/<id>/.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ra import core  # noqa: E402

DIGITS = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]


def camel(s: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", s)
    out = ""
    for p in parts:
        if not p:
            continue
        p = re.sub(r"\d", lambda m: DIGITS[int(m.group(0))], p)
        out += p[0].upper() + p[1:]
    return out


def flatten(d: dict, prefix: str = "") -> dict:
    out = {}
    for k, v in d.items():
        if k.startswith("_"):
            continue
        key = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            out.update(flatten(v, key))
        elif isinstance(v, (int, float, str, bool)):
            out[key] = v
    return out


def fmt(v, spec: str | None) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return f"{v:{spec}}" if spec else str(v)
    if isinstance(v, float):
        s = f"{v:{spec or '.4g'}}"
        if "e" in s:
            mant, exp = s.split("e")
            s = f"{mant}\\times 10^{{{int(exp)}}}"
            return f"\\ensuremath{{{s}}}"
        return s
    return re.sub(r"([#$%&_{}])", r"\\\1", str(v))


def main() -> int:
    ap = argparse.ArgumentParser(prog="./ra results-tex", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.parse_args()
    lines = ["% AUTO-GENERATED by `./ra results-tex` from results/*/metrics.json - DO NOT EDIT.",
             "% Every macro below traces to the file named in its comment.", ""]
    seen, n = {}, 0
    gen = core.path("paper", "generated")
    rdir = core.path("results")
    for mfile in sorted(rdir.glob("*/metrics.json")) if rdir.exists() else []:
        rid = mfile.parent.name
        if rid.startswith("_"):
            continue
        data = json.loads(mfile.read_text(encoding="utf-8"))
        formats = data.get("_format", {}) if isinstance(data, dict) else {}
        for key, val in flatten(data).items():
            name = "res" + camel(rid) + camel(key)
            if name in seen:
                print(f"warning: macro name clash {name} ({seen[name]} vs results/{rid}:{key}); skipped", file=sys.stderr)
                continue
            seen[name] = f"results/{rid}:{key}"
            lines.append(f"\\providecommand{{\\{name}}}{{{fmt(val, formats.get(key))}}} % results/{rid}/metrics.json : {key}")
            n += 1
        for snip in mfile.parent.glob("*.tex"):
            dest = gen / rid / snip.name
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(snip, dest)
    core.write_text(gen / "results.tex", "\n".join(lines) + "\n")
    print(f"wrote paper/generated/results.tex ({n} macros). Use them in prose instead of typing numbers.")
    for name, src in seen.items():
        print(f"  \\{name:<40} <- {src}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
