"""./ra verify-bib — every \\cite{} must resolve to a verified bibliography entry.

Offline checks (default, fast; run by the post-edit hook after every paper/ edit):
  MISSING      cited key not in paper/references.bib
  UNVERIFIED   entry not fetched by `./ra fetch-bib` (no ledger record)
  TAMPERED     entry content differs from what was fetched (hand/model edit)
  NO-ID        entry has neither DOI nor arXiv eprint
  FOREIGN-BIB  paper uses a .bib file other than paper/references.bib
  DUPLICATE-*  duplicate keys (error) / DOIs (warning)
--online     re-resolve every cited DOI/arXiv id: title/year/author match, retraction status (OpenAlex)
--claims     triage citing sentences against the cited abstract; flags possible non-support
--report F   also write a markdown report (e.g. reviews/internal/citation-report.md)
Exit status: 0 = no errors, 1 = errors found.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ra import bibcheck, core  # noqa: E402


def markdown(rep: dict) -> str:
    out = [f"# Citation verification report", "", f"_Generated by `./ra verify-bib` on {core.now()}_", "",
           f"- cited keys: {rep['cited_keys']}", f"- bibliography entries: {rep['bib_entries']}",
           f"- errors: {len(rep['errors'])}", f"- warnings: {len(rep['warnings'])}", ""]
    for level in ("errors", "warnings", "info"):
        if rep[level]:
            out.append(f"## {level.capitalize()}")
            for it in rep[level]:
                out.append(f"- **{it['code']}** `{it['key']}`: {it['msg']}" +
                           (f" ({', '.join(it['where'][:5])})" if it["where"] else ""))
            out.append("")
    if rep.get("claims"):
        flagged = [c for c in rep["claims"] if c["flags"]]
        out += ["## Claim-support triage", "",
                f"{len(rep['claims'])} citation contexts checked lexically against cited abstracts; "
                f"{len(flagged)} flagged. The agent must read each flagged source and record a verdict "
                "(SUPPORTED / PARTIAL / NOT SUPPORTED → fixed) below.", ""]
        for c in flagged:
            out.append(f"### {c['file']}:{c['line']} — `{c['key']}`")
            out.append(f"- Cited work: {c.get('title') or '?'}")
            out.append(f"- Sentence: \"{c['sentence']}\"")
            out.append(f"- Flags: {'; '.join(c['flags'])}")
            out.append("- Verdict: _TODO (agent)_")
            out.append("")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(prog="./ra verify-bib", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--online", action="store_true", help="re-resolve identifiers against the registries")
    ap.add_argument("--claims", action="store_true", help="triage claim support against cited abstracts")
    ap.add_argument("--threshold", type=float, default=0.12, help="claim-support overlap threshold")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--report", help="write a markdown report to this path")
    ap.add_argument("--quiet", action="store_true", help="print only on errors")
    a = ap.parse_args()

    rep = bibcheck.check(online=a.online, claims=a.claims, claim_threshold=a.threshold)
    if a.report:
        core.write_text(core.resolve_arg(a.report), markdown(rep))
    if a.json:
        print(json.dumps(rep, indent=2, ensure_ascii=False))
    elif not (a.quiet and not rep["errors"]):
        print(bibcheck.format_report(rep))
    return 1 if rep["errors"] else 0


if __name__ == "__main__":
    sys.exit(main())
